// Test-only transport: never sends a request to OpenAI or accepts real credentials.
const realFetch = window.fetch.bind(window);
window.apiMockCalls = [];
window.apiMockMode = 'complete';
window.fetch = async function (url, options) {
  if (String(url) !== 'https://api.openai.com/v1/responses') return realFetch(url, options);
  if (options.headers.Authorization !== 'Bearer qa-fake-key')
    throw Error('Test fixture only accepts fake key');
  const body = JSON.parse(options.body),
    input = JSON.parse(body.input[0].content[0].text);
  window.apiMockCalls.push({ body, selection: input.selection });
  if (window.apiMockMode === 'wait')
    return new Promise((resolve, reject) =>
      options.signal.addEventListener('abort', () =>
        reject(new DOMException('Aborted', 'AbortError')),
      ),
    );
  const candidate = {
    name: 'API candidate ' + input.variant_number,
    summary: 'Generated by deterministic QA transport',
    patches: [
      {
        type: 'style',
        element_id: input.selection[0],
        properties: [{ name: 'border-radius', value: input.variant_number * 6 + 'px' }],
        text: null,
        attributes: null,
        html: null,
        parent_id: null,
        before_id: null,
        css: null,
      },
    ],
  };
  const response = {
    status: 'completed',
    output: [{ content: [{ type: 'output_text', text: JSON.stringify(candidate) }] }],
    usage: { input_tokens: 100, output_tokens: 200 },
  };
  return new Response(
    'data: ' + JSON.stringify({ type: 'response.completed', response }) + '\n\n',
    { headers: { 'Content-Type': 'text/event-stream' } },
  );
};
